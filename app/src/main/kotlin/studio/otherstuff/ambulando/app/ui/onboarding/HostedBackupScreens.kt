/** The plain-language warning shown before any hosted backup is made and before any funding. Not a checkbox label alone: it is read in full. */
internal const val BACKUP_WARNING =
    "Your new identity is a key that only exists on this phone. NStack keeps a copy that is locked with the password you choose now. " +
        "NStack never sees that password or your key, and there is no reset: if you lose the password, nobody, including NStack and the app's makers, can unlock the copy. " +
        "If you also lose this phone's copy, or this backup, the identity and anything tied to it are gone for good."

/**
 * Mandatory hosted backup of a key generated by this app. Collects a username (permanent on that NStack) and a backup password
 * twice, then [HostedBackupController.save] encrypts on the device, uploads only the ciphertext and proves the copy opens. Nothing
 * counts until that proof is durable. The password lives only in this composable's memory and is cleared after every attempt.
 */
@Composable
internal fun HostedBackupCard(backup: HostedBackupController, run: (suspend () -> Unit) -> Unit) {
    val s by backup.snapshots.collectAsState()
    var username by remember { mutableStateOf("") }
    var password by remember { mutableStateOf("") }
    var confirm by remember { mutableStateOf("") }
    var understood by remember { mutableStateOf(false) }
    var fileNote by remember { mutableStateOf<String?>(null) }
    val context = LocalContext.current
    val picker = rememberLauncherForActivityResult(ActivityResultContracts.CreateDocument("text/plain")) { uri ->
        val text = backup.savedCiphertext()
        if (uri == null || text == null) { fileNote = "No file was saved."; return@rememberLauncherForActivityResult }
        fileNote = try {
            context.contentResolver.openOutputStream(uri, "wt")!!.use { it.write((text + "\n").toByteArray()) }
            val back = context.contentResolver.openInputStream(uri)!!.use { it.readBytes().toString(Charsets.UTF_8).trim() }
            if (back == text) "Saved a copy of the encrypted backup to the file you chose." else "The file did not save correctly. Choose another place."
        } catch (e: Exception) { "The file could not be saved. Choose another place." }
    }
    val amb = Amb.colors
    Column(Modifier.ambCard(amb).fillMaxWidth().testTag("backup.card"), verticalArrangement = Arrangement.spacedBy(12.dp)) {
        Text(
            if (s.stage == HostedBackupStage.CONFIRMED) "Identity backup saved" else "Back up your new identity",
            style = EditorialStyle, color = amb.primary, modifier = Modifier.semantics { heading() },
        )
        if (s.stage == HostedBackupStage.CONFIRMED) {
            Notice(NoticeTone.SUCCESS, "Your encrypted backup is saved on this NStack as ${s.username} and was checked: it opens with your password and belongs to this identity.",
                Modifier.testTag("backup.done"))
            OutlinedButton(onClick = { picker.launch("ambulando-identity-backup.txt") }, modifier = Modifier.fillMaxWidth().heightIn(min = 48.dp).testTag("backup.file")) {
                Text("Also save an encrypted copy to a file")
            }
            fileNote?.let { Text(it, style = MaterialTheme.typography.bodySmall, color = amb.mutedForeground, modifier = Modifier.testTag("backup.file.note")) }
            return@Column
        }
        Notice(NoticeTone.WARNING, BACKUP_WARNING, Modifier.testTag("backup.warning"))
        Text(
            "The copy is stored under a username that cannot be changed later. Anyone who knows the username can download the locked copy and try to guess the password offline, as many times as they like, so the password must be long and unique.",
            style = MaterialTheme.typography.bodySmall, color = amb.mutedForeground,
        )
        OutlinedTextField(username, { username = it }, singleLine = true, label = { Text("Username") }, modifier = Modifier.fillMaxWidth().testTag("backup.username"),
            keyboardOptions = KeyboardOptions(autoCorrectEnabled = false), supportingText = { Text("3 to 32 letters, numbers, - or _") })
        OutlinedTextField(password, { password = it }, singleLine = true, label = { Text("Backup password") }, visualTransformation = PasswordVisualTransformation(),
            keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Password, autoCorrectEnabled = false), modifier = Modifier.fillMaxWidth().testTag("backup.password"),
            supportingText = { Text("At least 16 characters. Use a long, unique phrase you use nowhere else.") })
        OutlinedTextField(confirm, { confirm = it }, singleLine = true, label = { Text("Repeat the password") }, visualTransformation = PasswordVisualTransformation(),
            keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Password, autoCorrectEnabled = false), modifier = Modifier.fillMaxWidth().testTag("backup.confirm"))
        Row(verticalAlignment = Alignment.CenterVertically, modifier = Modifier.fillMaxWidth().heightIn(min = 48.dp)) {
            Checkbox(understood, { understood = it }, modifier = Modifier.testTag("backup.understood").semantics { stateDescription = if (understood) "Understood" else "Not yet understood" })
            Text("I understand there is no password reset and no recovery if I lose the password and the backup.", Modifier.padding(start = 8.dp), style = MaterialTheme.typography.bodyMedium)
        }
        s.failure?.let { Notice(NoticeTone.ERROR, it.userMessage, Modifier.semantics { liveRegion = LiveRegionMode.Polite }.testTag("backup.failure")) }
        if (s.stage == HostedBackupStage.PENDING && s.failure == null) {
            Notice(NoticeTone.INFO, "A backup was started but not yet confirmed, so it does not count. Enter the same password to continue.", Modifier.testTag("backup.pending"))
        }
        PrimaryButton(if (s.busy) "Saving and checking…" else "Save encrypted backup", enabled = understood && username.isNotBlank() && password.isNotEmpty() && !s.busy,
            modifier = Modifier.heightIn(min = 48.dp).testTag("backup.save"), onClick = {
                val u = username; val p = password; val c = confirm
                password = ""; confirm = ""                      // the fields never keep a secret across an attempt
                run { backup.save(u, p, c) }
            })
        if (s.busy) CircularProgressIndicator()
    }
}
