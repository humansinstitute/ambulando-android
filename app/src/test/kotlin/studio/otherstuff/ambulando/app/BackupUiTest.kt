private const val INVITE = "inv_AbCdEfGh12345678"
private const val PASSWORD = "correct horse battery staple 42"

/** Compose states for a key generated by this app: payment is gated until the hosted, password-encrypted copy is proven. */
@RunWith(RobolectricTestRunner::class)
@GraphicsMode(GraphicsMode.Mode.NATIVE)
class BackupUiTest {
    @get:Rule val compose = createComposeRule()
    private val scope = CoroutineScope(Dispatchers.Default)
    private val secret = ByteArray(32) { 0x51 }
    private val npub = NostrKeys.npub(NostrKeys.publicKeyHex(secret))!!
    private val tower = FakeOnboardingTower().also { it.newInvite(INVITE) }
    private val backup = HostedBackupController(TowerOrigin(tower.origin), npub, { NostrKeys.sign(it, secret) }, {}, { p, n -> Nip49.encrypt(secret, p, n) }, tower, MemoryHostedBackupStore())
    private val controller = OnboardingController(
        TowerOrigin(tower.origin), npub, { NostrKeys.sign(it, secret) }, {}, tower, MemoryOnboardingDraftStore(),
        identityGate = backup.gate(IdentityOrigin.NEW),
    )

    private fun waitFor(tag: String) = compose.waitUntil(30_000) { compose.onAllNodes(hasTestTag(tag)).fetchSemanticsNodes().isNotEmpty() }
    private fun tap(tag: String) { compose.onNodeWithTag(tag).performScrollTo().performClick() }

    private fun show() = compose.setContent {
        AmbulandoTheme { OnboardingWizard(controller, launch = { scope.launch { it() } }, isConnected = { false }, connect = {}, onFinished = {}, backup = backup) }
    }

    @Test fun payStaysOffUntilTheBackupIsSavedAndCheckedThenOpens() {
        show()
        waitFor("onboarding.name")
        compose.onNodeWithTag("onboarding.name").performTextInput("Studio")
        compose.onNodeWithTag("onboarding.invite").performTextInput(INVITE)
        tap("onboarding.review"); waitFor("onboarding.pay")

        // The explicit warning is on screen before any funding, and the save button needs the acknowledgement.
        compose.onNodeWithTag("backup.warning").assertExists()
        compose.onNodeWithText("there is no reset", substring = true).assertExists()
        compose.onNodeWithTag("onboarding.pay").assertIsNotEnabled()
        compose.onNodeWithTag("backup.username").performScrollTo().performTextInput("alice")
        compose.onNodeWithTag("backup.password").performTextInput(PASSWORD)
        compose.onNodeWithTag("backup.confirm").performTextInput(PASSWORD)
        compose.onNodeWithTag("backup.save").performScrollTo().assertIsNotEnabled()
        tap("backup.understood")
        compose.onNodeWithTag("backup.save").assertIsEnabled().assertHeightIsAtLeast(48.dp)
        assertTrue("nothing is hosted or created yet", tower.backups.isEmpty() && tower.mutations().isEmpty())

        tap("backup.save")
        waitFor("backup.done")
        assertEquals(HostedBackupStage.CONFIRMED, backup.snapshot().stage)
        assertEquals(1, tower.backups.size)
        compose.waitUntil(30_000) { runCatching { compose.onNodeWithTag("onboarding.pay").assertIsEnabled(); true }.getOrDefault(false) }
        // No plaintext secret anywhere on screen; the password fields were cleared after the attempt.
        assertTrue(compose.onAllNodes(hasText(PASSWORD, substring = true)).fetchSemanticsNodes().isEmpty())
    }

    @Test fun aRefusedBackupShowsAFriendlyReasonAndKeepsPaymentOff() {
        tower.backupThrottled = true
        show()
        waitFor("onboarding.name")
        compose.onNodeWithTag("onboarding.name").performTextInput("Studio")
        compose.onNodeWithTag("onboarding.invite").performTextInput(INVITE)
        tap("onboarding.review"); waitFor("backup.username")
        compose.onNodeWithTag("backup.username").performScrollTo().performTextInput("alice")
        compose.onNodeWithTag("backup.password").performTextInput(PASSWORD)
        compose.onNodeWithTag("backup.confirm").performTextInput(PASSWORD)
        tap("backup.understood"); tap("backup.save")
        waitFor("backup.failure")
        compose.onNodeWithTag("onboarding.pay").assertIsNotEnabled()
        assertTrue(tower.mutations().isEmpty())
    }

    /** UI evidence: PNGs of the real backup screens (native graphics, not a device) under build/ (not committed). */
    @Test fun capturesBackupScreensForEvidence() {
        val dir = java.io.File("build/onboarding-evidence").also { it.mkdirs() }
        fun shot(name: String) = java.io.FileOutputStream(java.io.File(dir, "$name.png")).use { compose.onRoot().captureToImage().asAndroidBitmap().compress(android.graphics.Bitmap.CompressFormat.PNG, 100, it) }
        show()
        waitFor("onboarding.name")
        compose.onNodeWithTag("onboarding.name").performTextInput("Studio")
        compose.onNodeWithTag("onboarding.invite").performTextInput(INVITE)
        waitFor("backup.warning"); shot("3-backup-required-form")
        tap("onboarding.review"); waitFor("onboarding.pay"); shot("4-review-pay-off-until-backup")
        compose.onNodeWithTag("backup.username").performScrollTo().performTextInput("alice")
        compose.onNodeWithTag("backup.password").performTextInput(PASSWORD)
        compose.onNodeWithTag("backup.confirm").performTextInput(PASSWORD)
        tap("backup.understood"); tap("backup.save"); waitFor("backup.done"); shot("5-backup-confirmed")
        assertTrue(java.io.File(dir, "5-backup-confirmed.png").length() > 1000)
    }
}
